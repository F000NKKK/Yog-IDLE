/// Where the generated names go, from this crate.
const YOG_IDS_TS: &str = "../src/data/yogIds.generated.ts";
const PLUGINS_TS: &str = "../src/plugins.generated.ts";

/// Writes `text` to `path` unless it's there already (no rebuild loop).
fn write(path: &str, text: &str) {
    if std::fs::read_to_string(path).ok().as_deref() != Some(text) {
        std::fs::write(path, text).expect("src/ is writable");
    }
}

/// The plugins' names for the front end: `plugins.<key>`.
fn plugins_ts() -> String {
    let mut out = String::from("// Generated by src-tauri/build.rs from src/plugin_names.rs — don't edit.\n\n/** Yog IDLE's plugins: their commands are `plugin:<name>|<command>`. */\nexport const plugins = {\n");
    for (key, name, _) in PLUGINS {
        out.push_str(&format!("  {key}: {name:?},\n"));
    }
    out.push_str("} as const;\n");
    out
}

fn main() {
    write(YOG_IDS_TS, &yog_ids::export::typescript());
    write(PLUGINS_TS, &plugins_ts());
    let attributes = PLUGINS.iter().fold(Attributes::new(), |attributes, (_, name, commands)| {
        attributes.plugin(name, InlinedPlugin::new().commands(commands).default_permission(DefaultPermissionRule::AllowAllCommands))
    });
    tauri_build::try_build(attributes).expect("tauri build");
}
