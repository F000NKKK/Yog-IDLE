import { extensionOf } from "substrate-platform-ui";
import { t } from "substrate-platform-ui";
import { formats } from "./yogFileTypes";

/** Whether `path` is `ancestor` itself or anywhere beneath it. */
export function isWithin(path: string, ancestor: string): boolean {
  if (path === ancestor) return true;
  const base = ancestor.replace(/[/\\]+$/, "");
  return path.startsWith(`${base}/`) || path.startsWith(`${base}\\`);
}

/** The mod a file in it belongs to: the folder holding the `src/`, `resources/` or `content/` it's in. */
export function modRootOf(path: string): string | null {
  const m = /^(.*)[\\/](?:src|resources|content)[\\/]/.exec(path);
  return m ? m[1] : null;
}

/** The folder `path` sits in. */
export function parentOf(path: string): string {
  return path.replace(/[/\\][^/\\]*$/, "");
}

/** Whether two paths name the same file — separators normalized, and a relative path (as debug info sometimes records, e.g. `src/lib.rs`) matches an absolute one ending in it. */
export function samePath(a: string, b: string): boolean {
  const norm = (p: string) => p.replace(/\\/g, "/").replace(/\/+$/, "");
  const x = norm(a);
  const y = norm(b);
  return x === y || x.endsWith(`/${y}`) || y.endsWith(`/${x}`);
}

/** A name for a new/renamed file or folder: `null` if usable, else why not (`""` for blank — nothing worth saying). */
export function validateEntryName(value: string): string | null {
  const name = value.trim();
  if (!name) return "";
  if (/[/\\]/.test(name)) return t("A name can't contain / or \\.");
  if (name === "." || name === "..") return t("Not a valid name.");
  return null;
}

/** `path` with its last segment replaced by `name` — where a rename moves it. */
export function renamedPath(path: string, name: string): string {
  return path.replace(/[^/\\]+$/, name);
}

/** Where `yog` generates screen code, under a mod project's root. */
const GENERATED_DIR = ".yog-build/generated";

/**
 * The generated code of `path` in the project at `root`, or `null`:
 * - screen `src/foo/bar.yui` → `<root>/.yog-build/generated/foo/bar.g.rs`
 *   (what `yog ui gen` writes and `yog_api::ui_include!("foo/bar")` pulls in);
 * - resource set `resources/[…/]Strings.yres` (the neutral file, not a
 *   culture variant like `Strings.ru_ru.yres`) →
 *   `<root>/.yog-build/generated/resources/Strings.g.rs` (included by
 *   `yog_api::resources!()`).
 */
export function generatedCodePath(root: string, path: string): string | null {
  const sep = root.includes("\\") && !root.includes("/") ? "\\" : "/";
  const base = root.replace(/[/\\]+$/, "");
  const join = (...parts: string[]) => [base, ...GENERATED_DIR.split("/"), ...parts].join(sep).replace(/[/\\]/g, sep);
  const ext = extensionOf(path);
  if (ext === formats.res.ext) {
    if (!isWithin(path, `${base}${sep}resources`)) return null;
    const set = /([^/\\]+)\.yres$/i.exec(path)?.[1];
    return set && !set.includes(".") ? join("resources", `${set}.g.rs`) : null;
  }
  const src = `${base}${sep}src`;
  if (!isWithin(path, src) || ext !== formats.ui.ext) return null;
  const rel = path.slice(src.length + 1).replace(/\.yui$/i, "");
  return join(`${rel}.g.rs`);
}

/** Whether `path` is generated code (`.yog-build/generated/**`), opened read-only with a notice. */
export function isGeneratedCode(path: string): boolean {
  return GENERATED_CODE.test(path);
}

const GENERATED_CODE = /^(.*?)[/\\]\.yog-build[/\\]generated[/\\](.+)\.g\.rs$/i;
/** `yog`'s header line: "Generated by `yog build` from <source> — …" / "Generated by yog from <source> (view model …) —". */
const GENERATED_FROM = /Generated by (?:`yog build`|yog) from (.+?)(?:\s+\(|\s+—|,|$)/m;

/** What a generated file was generated from. */
export interface GeneratedSource {
  /** The source as `yog` names it, relative to the mod root — one file (`src/ui/main.yui`) or a glob over many. */
  source: string;
  /** The absolute path of `source` when it's a single file, to open it. */
  file: string | null;
}

/**
 * The source of the generated file at `path` — from the header `yog` writes
 * at its top (`content`), else from where it lives (`generated/<rel>.g.rs`
 * is screen `src/<rel>.yui`, `generated/resources/<Set>.g.rs` resource set
 * `resources/<Set>.yres`). `null` when neither says.
 */
export function generatedSource(path: string, content: string): GeneratedSource | null {
  const match = GENERATED_CODE.exec(path);
  if (!match) return null;
  const [, root, rel] = match;
  const sep = path.includes("\\") && !path.includes("/") ? "\\" : "/";
  let source = GENERATED_FROM.exec(content.slice(0, 1024))?.[1]?.trim() ?? null;
  if (!source) {
    const relPath = rel.replace(/\\/g, "/");
    const set = /^resources\/([^/]+)$/.exec(relPath)?.[1];
    if (set) source = `resources/${set}.yres`;
    else if (relPath.includes("/")) source = `src/${relPath}.yui`;
  }
  if (!source) return null;
  // Only one file can be opened: not a glob, a list or a directory.
  const file = source.includes("*") || source.includes(" ") || source.endsWith("/") ? null : [root, ...source.split("/")].join(sep);
  return { source, file };
}
