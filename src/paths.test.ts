import { describe, expect, it } from "vitest";
import { generatedSource } from "./paths";

const GEN = "/mods/hex/.yog-build/generated";

describe("generatedSource", () => {
  it("reads the source from yog's header", () => {
    const screen = "// <auto-generated>\n//     Generated by yog from src/ui/spellcasting.yui (view model SpellcastingVm, codegen 1) —\n";
    expect(generatedSource(`${GEN}/ui/spellcasting.g.rs`, screen)).toEqual({ source: "src/ui/spellcasting.yui", file: "/mods/hex/src/ui/spellcasting.yui" });

    const set = "// <auto-generated>\n//     Generated by `yog build` from resources/Blocks.yres — don't edit,\n";
    expect(generatedSource(`${GEN}/resources/Blocks.g.rs`, set)).toEqual({ source: "resources/Blocks.yres", file: "/mods/hex/resources/Blocks.yres" });
  });

  it("names a glob source without a file to open", () => {
    const all = "// <auto-generated>\n//     Generated by `yog build` from resources/**/*.yres — don't edit,\n";
    expect(generatedSource(`${GEN}/resources.g.rs`, all)).toEqual({ source: "resources/**/*.yres", file: null });
    const content = "//     Generated by `yog build` from content/**/*.yblock and *.yitem — don't edit,\n";
    expect(generatedSource(`${GEN}/yog-content.g.rs`, content)?.source).toBe("content/**/*.yblock and *.yitem");
  });

  it("falls back to path conventions, then to nothing", () => {
    expect(generatedSource(`${GEN}/ui/main.g.rs`, "")?.file).toBe("/mods/hex/src/ui/main.yui");
    expect(generatedSource(`${GEN}/resources/Strings.g.rs`, "")?.file).toBe("/mods/hex/resources/Strings.yres");
    expect(generatedSource(`${GEN}/components.g.rs`, "// <auto-generated> by yog: component .yui files")).toBeNull();
    expect(generatedSource("/mods/hex/src/lib.rs", "")).toBeNull();
  });

  it("keeps Windows separators", () => {
    const set = "Generated by `yog build` from resources/Items.yres — don't edit";
    expect(generatedSource("C:\\mods\\hex\\.yog-build\\generated\\resources\\Items.g.rs", set)?.file).toBe("C:\\mods\\hex\\resources\\Items.yres");
  });
});
